/**
 * Validates every file in data/ and compiles it into src/generated/.
 *
 *   pnpm data:build          validate + generate
 *   pnpm data:check          validate only (CI); fails on unsorted or non-canonical files
 *   tsx scripts/build-data.ts --fix   rewrite data files in canonical sorted form
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { DatasetMetaSchema } from '../src/lib/dataset-meta';
import { datasets, derive } from './datasets';
import { formatJson } from './lib/json';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'data');
const outDir = join(root, 'src/generated');
const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check');
const fix = args.has('--fix');

const errors: string[] = [];

function moduleSource(value: unknown, typeName: string, imports: string[]): string {
  // JSON.parse of a string literal is faster for V8 to load than an object literal.
  const literal = JSON.stringify(JSON.stringify(value));
  return `// Generated by scripts/build-data.ts. Do not edit.\n${imports.join('\n')}\n\nconst data: ${typeName} = JSON.parse(${literal});\nexport default data;\n`;
}

function formatIssues(file: string, error: z.ZodError, records: unknown[]): string[] {
  return error.issues.slice(0, 20).map((i) => {
    const [index, ...rest] = i.path;
    const record =
      typeof index === 'number' ? (records[index] as Record<string, unknown>) : undefined;
    const id = record ? (record.slug ?? record.postcode ?? record.id ?? index) : index;
    return `${file} [${String(id)}] ${rest.join('.')}: ${i.message}`;
  });
}

async function main() {
  const metaRaw = await readFile(join(dataDir, 'meta.json'), 'utf8');
  const meta = z.array(DatasetMetaSchema).safeParse(JSON.parse(metaRaw));
  if (!meta.success) {
    errors.push(...formatIssues('meta.json', meta.error, JSON.parse(metaRaw)));
  }
  const metaByKey = Object.fromEntries((meta.data ?? []).map((m) => [m.dataset, m]));

  const loaded: Record<string, any[]> = {};
  for (const spec of datasets) {
    const path = join(dataDir, spec.file);
    const raw = await readFile(path, 'utf8').catch(() => null);
    if (raw === null) {
      errors.push(`${spec.file}: missing`);
      continue;
    }
    const records = JSON.parse(raw) as unknown[];
    const parsed = z.array(spec.schema).safeParse(records);
    if (!parsed.success) {
      errors.push(...formatIssues(spec.file, parsed.error, records));
      continue;
    }
    const rows = parsed.data as any[];

    const keys = rows.map(spec.sortKey);
    const dupes = keys.filter((k, i) => keys.indexOf(k) !== i);
    if (dupes.length)
      errors.push(`${spec.file}: duplicate keys ${[...new Set(dupes)].slice(0, 5).join(', ')}`);

    const sorted = [...records].sort((a, b) => {
      const ka = spec.sortKey(a);
      const kb = spec.sortKey(b);
      return ka < kb ? -1 : ka > kb ? 1 : 0;
    });
    const canonical = formatJson(sorted);
    if (raw !== canonical) {
      if (fix) {
        await writeFile(path, canonical);
        console.log(`fixed ${spec.file}`);
      } else {
        errors.push(
          `${spec.file}: not sorted/canonical (run: pnpm tsx scripts/build-data.ts --fix)`,
        );
      }
    }
    if (!metaByKey[spec.key]) errors.push(`meta.json: no entry for dataset '${spec.key}'`);
    loaded[spec.key] = rows;
  }

  const { errors: integrity, outputs } = derive(loaded);
  errors.push(...integrity);

  if (errors.length) {
    console.error(`✗ ${errors.length} data error(s):\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  if (checkOnly) {
    console.log(`✓ ${datasets.length} datasets valid`);
    return;
  }

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  for (const spec of datasets) {
    const source = moduleSource(loaded[spec.key], `${spec.type.name}[]`, [
      `import type { ${spec.type.name} } from '${spec.type.from}';`,
    ]);
    await writeFile(join(outDir, `${spec.key}.ts`), source);
  }
  for (const out of outputs) {
    const imports = out.typeImport
      ? [`import type { ${out.typeImport.names.join(', ')} } from '${out.typeImport.from}';`]
      : [];
    await writeFile(join(outDir, `${out.name}.ts`), moduleSource(out.value, out.type, imports));
  }
  await writeFile(
    join(outDir, 'meta.ts'),
    moduleSource(metaByKey, 'Record<string, DatasetMeta>', [
      `import type { DatasetMeta } from '../lib/dataset-meta';`,
    ]),
  );
  console.log(`✓ generated ${datasets.length} datasets + ${outputs.length} derived outputs`);
}

await main();
